def test_selected_json_credential_is_only_fallback_and_never_default_discovery(
    profile, monkeypatch
):
    credential = profile[0].parent / "selected.json"
    credential.write_text(json.dumps({"selected_key": "synthetic-file-key"}))
    profile[1]["api"]["credential"].update(file=str(credential), json_key="selected_key")
    save(profile)
    settings = config.load(profile[0])
    assert config.credential_value(settings) == "synthetic-selected-key"
    monkeypatch.delenv("SYNTHETIC_TRANSLATION_KEY")
    assert config.credential_value(settings) == "synthetic-file-key"
    credential.unlink()
    assert config.credential_value(settings) is None


