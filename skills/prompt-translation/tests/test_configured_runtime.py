def save(profile):
    profile[0].write_text(json.dumps(profile[1]))


def source(profile, name="2026-01-01_session.md", prompts=None):
    prompts = prompts or [
        (
            "2026-01-01 01:00:00Z",
            "这是一个用于验证完整翻译与增量复用行为的中文提示，其中包含完整的理由与计划。",
        )
    ]
    path = profile[2] / "sources/prompts" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(f"### {timestamp}\n\n{body}" for timestamp, body in prompts))
    return path


def run(profile, *args):
    return translate.main(["--config", str(profile[0]), *args])


class FakeMessages:
    def __init__(self, replies):
        self.replies = iter(replies)
        self.calls = []

    def create(self, **request):
        self.calls.append(request)
        return SimpleNamespace(content=[SimpleNamespace(text=next(self.replies))])


def fake_client(monkeypatch, replies):
    client = SimpleNamespace(messages=FakeMessages(replies))
    monkeypatch.setattr(translate, "make_client", lambda *a: (client, "synthetic"))
    return client


def validate_file(profile, filename):
    validation.configure(config.load(profile[0]))
    return validation.validate(profile[2] / "learning/pairs" / filename)


def test_config_preserves_prompt_bytes_revision_and_timestamp(profile, monkeypatch):
    source(profile)
    profile[1]["pipeline_revision"] = 2
    profile[1]["prompts"]["translate"] = "  Exact caller text.\nWith a final newline.\n"
    profile[1]["generated_marker"] = "<!-- Generated by a-caller-command."
    save(profile)
    client = fake_client(monkeypatch, ['["Translated result."]'])
    assert run(profile, "--date", "2026-01-01", "--no-classify") == 0
    request = client.messages.calls[0]
    assert request["system"][0]["text"] == profile[1]["prompts"]["translate"]
    assert request["system"][0]["cache_control"] == {"type": "ephemeral"}
    output = profile[2] / "learning/pairs/2026-01-01.md"
    assert "2026-01-01 01:00:00Z" in output.read_text()
    assert "pipeline_revision: 2" in output.read_text()
    assert profile[1]["generated_marker"] in output.read_text()
    assert validate_file(profile, "2026-01-01.md") == []


def test_committed_day_reuses_unchanged_translations_after_cache_loss_and_move(
    profile, monkeypatch
):
    original = source(profile)
    fake_client(monkeypatch, ['["Existing translation."]'])
    assert run(profile, "--date", "2026-01-01", "--no-classify") == 0
    original_text = original.read_text()
    original.unlink()
    moved = profile[2] / "sources/prompts/2026-01/2026-01-02_session.md"
    moved.parent.mkdir()
    moved.write_text(
        original_text
        + "\n\n### 2026-01-01 02:00:00Z\n\n这是新到达的第二个中文提示，用于验证旧记录可以继续复用而无需重新支付翻译费用。"
    )
    (profile[2] / "learning/pairs/.translate_state.json").unlink()
    client = fake_client(monkeypatch, ['["Only the new record is translated."]'])
    assert run(profile, "--date", "2026-01-01", "--no-classify") == 0
    assert len(client.messages.calls) == 1
    assert "新到达" in client.messages.calls[0]["messages"][0]["content"]
    output = profile[2] / "learning/pairs/2026-01-01.md"
    assert "Existing translation." in output.read_text()
    assert validate_file(profile, "2026-01-01.md") == []


def test_failed_day_preserves_completed_day_without_repeat_calls(profile, monkeypatch):
    source(profile)
    source(
        profile,
        "2026-01-02_next.md",
        [
            (
                "2026-01-02 01:00:00Z",
                "这是第二天的中文提示，需要完整解释故障恢复如何保留已经完成的有效结果。",
            )
        ],
    )
    client = fake_client(monkeypatch, ['["First day done."]', "not-json"])
    args = [
        "--since",
        "2026-01-01",
        "--through-date",
        "2026-01-02",
        "--oldest-first",
        "--no-classify",
    ]
    assert run(profile, *args) == 1
    assert len(client.messages.calls) == 2
    output = profile[2] / "learning/pairs"
    assert (output / "2026-01-01.md").exists() and not (output / "2026-01-02.md").exists()
    before = (output / "2026-01-01.md").read_bytes()
    recovered = fake_client(monkeypatch, ['["Second day recovered."]'])
    assert run(profile, *args) == 0
    assert len(recovered.messages.calls) == 1
    assert (output / "2026-01-01.md").read_bytes() == before
    assert validate_file(profile, "2026-01-02.md") == []


